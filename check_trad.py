# Also check markdown files
md_dir = 'classics_markdown'
if os.path.exists(md_dir):
    for fn in os.listdir(md_dir):
        if fn.endswith('.md'):
            files_to_check.append(f'{md_dir}/{fn}')

total_trad = 0
for filepath in files_to_check:
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            lines = f.readlines()
        
        found = []
        for i, line in enumerate(lines):
            for ch in line:
                if ch in trad_to_simp:
                    found.append((i+1, ch, trad_to_simp[ch], line.strip()[:80]))
        
        if found:
            total_trad += len(found)
            print(f'\n=== {filepath} ({len(found)}个繁体字) ===')
            for ln, trad, simp, ctx in found[:20]:
                print(f'  行{ln}: "{trad}"→"{simp}" | {ctx}')
            if len(found) > 20:
                print(f'  ... 还有{len(found)-20}个')
    except Exception as e:
        print(f'Error reading {filepath}: {e}')

print(f'\n=== 总计: {total_trad}个繁体字 ===')
