# -*- coding: utf-8 -*-
import re
t = open('lib/translations.ts', encoding='utf-8').read()

def add(bid, items):
    m = re.search(r"['\"]?" + re.escape(bid) + r"['\"]?\s*:\s*\[", t)
    assert m, bid
    start = m.end()
    end = t.find('\n  ],', start)
    # 若数组最后一条已有逗号则不加，否则补
    insert = ''
    for i, item in enumerate(items):
        comma = ',' if i < len(items) - 1 else ''
        insert += "    '" + item + "'" + comma + "\n"
    t = t[:end] + '\n' + insert + t[end:]
    return t

