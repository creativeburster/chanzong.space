# Remove false positives (chars that are same in both)
# These are NOT traditional: 悟勤修究迷慧教住坐行道戒律善罪福智定念息善悔
false_positives = {'悟','勤','修','究','迷','慧','教','住','坐','行','道','戒','律','善','罪','福','智','定','念','息','悔','静','动','着','谷','豹','董','葛','赤','黑','默','鹿','麟','骨','高','解','警','譬','勤','业'}
for fp in false_positives:
    T2S.pop(fp, None)

# Also remove 圜 - it's a valid ancient variant used in 圜悟, not a trad char per se
T2S.pop('圜', None)

files_to_check = [
    'lib/taxonomy.ts',
    'lib/translations.ts',
    'lib/glossary.ts',
    'lib/stats.ts',
    'app/layout.tsx',
]

md_dir = 'classics_markdown'
if os.path.exists(md_dir):
    for fn in sorted(os.listdir(md_dir)):
        if fn.endswith('.md'):
            files_to_check.append(f'{md_dir}/{fn}')

total_trad = 0
results = []
for filepath in files_to_check:
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            lines = f.readlines()
        
        found = []
        for i, line in enumerate(lines):
            for ch in line:
                if ch in T2S:
                    found.append((i+1, ch, T2S[ch]))
        
        if found:
            total_trad += len(found)
            # Get unique chars
            unique_chars = {}
            for ln, trad, simp in found:
                if trad not in unique_chars:
                    unique_chars[trad] = []
                unique_chars[trad].append(ln)
            
            results.append((filepath, len(found), unique_chars))
    except Exception as e:
        print(f'Error reading {filepath}: {e}')

for filepath, count, unique_chars in results:
    print(f'\n=== {filepath} ({count}个繁体字) ===')
    for trad, lines_list in sorted(unique_chars.items()):
        simp = T2S[trad]
        print(f'  "{trad}"→"{simp}" ({len(lines_list)}处) 行: {lines_list[:10]}')

print(f'\n=== 总计: {total_trad}个繁体字 ===')
